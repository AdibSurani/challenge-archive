from Crypto.Cipher import AES
import os

FLAG = os.getenv('FLAG', 'oiccflag{?????????????????????????????????????}')

for _ in range(1337):
    iv = input('Give me an IV: ').encode()
    cipher = AES.new(key=os.urandom(16), mode=AES.MODE_CFB, iv=iv)
    enc = bytes(ord(x) ^ cipher.encrypt(b'b')[0] for x in FLAG)
    print(enc.hex())
